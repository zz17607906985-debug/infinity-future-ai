const assert = require('assert');
const index = require('../src/assets/smart-index');
assert.deepEqual(index.semanticCollections({name: '主角人像', tags: ['角色']}), ['character']);
assert.equal(index.matchesCollection({smartCollections: ['scene']}, 'scene', 2), true);
assert.equal(index.matchesCollection({}, 'unused', 0), true);
assert.equal(index.matchesCollection({}, 'unused', 1), false);
assert.equal(index.matchesCollection({visualFeature: {hash: '1'}}, 'indexed', 0), true);
const pixels = new Uint8ClampedArray(8 * 8 * 4).fill(255);
const feature = index.imageFeatureFromPixels(pixels, 8, 8);
assert.equal(feature.hash.length, 64);
assert.equal(index.featureDistance(feature, feature), 0);
assert.equal(index.featureDistance(null, feature), Infinity);
assert.equal(index.isValidFeature(feature), true);
assert.equal(index.queryIntent('找这个角色 小明').collection, 'character');
assert.equal(index.queryIntent('找相似构图').collection, 'shot');
assert.equal(index.queryIntent('找没有使用的素材').collection, 'unused');
assert.equal(index.matchesQuery({name: '小明角色正面', tags: ['角色']}, '找这个角色 小明', 1), true);
assert.equal(index.matchesQuery({name: '城市夜景', tags: ['场景']}, '找同一场景 夜景', 1), true);
assert.equal(index.matchesQuery({name: '废片'}, '找没有使用的素材', 0), true);
assert.equal(index.matchesQuery({name: '已用素材'}, '找没有使用的素材', 2), false);
const repaired = index.repairIndex([{name: '主角', visualFeature: {hash: 'bad'}}, {name: '场景', visualFeature: feature}]);
assert.equal(repaired.invalid, 1);
assert.equal(repaired.assets[0].visualFeature, null);
assert.equal(repaired.assets[1].visualFeature.hash.length, 64);
console.log('Asset smart index tests passed.');
