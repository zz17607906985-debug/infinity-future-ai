'use strict';

const assert = require('assert/strict');
const fs = require('fs');
const path = require('path');

const providerUi = fs.readFileSync(path.join(__dirname, '..', 'src', 'providers', 'provider-ui.js'), 'utf8');
const styles = fs.readFileSync(path.join(__dirname, '..', 'src', 'styles.css'), 'utf8');

const connect = providerUi.indexOf('class="api-provider-step api-provider-step-connect"');
const model = providerUi.indexOf('class="api-provider-step api-provider-step-model"');
const advanced = providerUi.indexOf('class="api-provider-more-options"');
assert.ok(connect >= 0 && model > connect, 'connection and model steps must follow the setup flow');
assert.equal(advanced, -1, 'advanced interface settings must not appear in the provider card');
assert.doesNotMatch(providerUi, /data-provider-field="concurrency"/, 'concurrency control must not be exposed');
assert.match(providerUi, /concurrency: Math\.max\(1, Math\.min\(4, Number\(provider\.concurrency \|\| 1\)\)\)/, 'saved concurrency remains intact');
assert.match(providerUi, /data-provider-save-key/);
assert.match(providerUi, /data-provider-import-models/);
assert.match(providerUi, /providerQuickKeyPoolHtml\(provider\)/);
assert.match(providerUi, /<option value="__auto__"/);
assert.match(providerUi, /function detectProviderProtocol\(/);
assert.match(providerUi, /function applyDetectedProviderProtocol\(/);
assert.match(providerUi, /function autoDetectProviderProtocol\(/);
assert.match(providerUi, /protocolMode: providerProtocolMode\(provider\)/);
assert.match(providerUi, /自动识别 · 保存时检测/);
assert.match(providerUi, /自动识别 · 待确认/);
assert.match(providerUi, /await autoDetectProviderProtocol\(provider, apiUrl, apiKey\)/);
assert.match(providerUi, /provider\.protocolMode = 'manual'/);
assert.match(providerUi, /function providerSetupResultHtml\(/);
assert.match(providerUi, /读取模型<\/strong><small>Key 保存后按需读取模型并选择可用能力/);
assert.match(providerUi, /自动分配/);
assert.match(providerUi, /读取模型/);
assert.match(providerUi, /data-provider-auto-configure/);
assert.match(providerUi, /data-provider-test-image/);
assert.match(providerUi, /data-provider-import-models/);
assert.doesNotMatch(providerUi, /\$\{providerSetupResultHtml\(provider\)\}/, 'redundant setup result block should not render in the main card');
assert.doesNotMatch(providerUi, /class="api-provider-setup-checks"/, 'redundant status checklist should not render in the main card');
assert.doesNotMatch(providerUi, /<button[^>]+data-provider-add-key/, 'API Key input and automatic save replace the duplicate add-key action');
assert.match(providerUi, /async function autoConfigureProviderFromCard/);
assert.match(providerUi, /class="api-provider-manager"/);
assert.match(providerUi, /class="api-provider-sidebar"/);
assert.match(providerUi, /data-provider-select/);
assert.match(providerUi, /host\.apiProviderUiSelectedId/);
assert.match(providerUi, /function prepareProviderKeyAddition/);
assert.doesNotMatch(providerUi, /providerAddMode/);
assert.match(providerUi, /saveProviderKeyFromCard\(card, true\)/);
assert.doesNotMatch(providerUi, /data-provider-key-select/);
assert.doesNotMatch(providerUi, /data-provider-model-key/);
assert.doesNotMatch(providerUi, /模型 Key/);
assert.match(providerUi, /新 Key 会自动追加到当前服务的 Key 池/);
assert.doesNotMatch(providerUi, /<details class="api-provider-more-options"\s+open/);
assert.equal((providerUi.match(/data-provider-field="apiUrl"/g) || []).length, 1, 'API address should only appear once per template');
assert.equal((providerUi.match(/data-provider-key-input type="password"/g) || []).length, 1, 'API Key field should only appear once per template');
assert.equal((providerUi.match(/data-provider-field="type"/g) || []).length, 0, 'advanced protocol picker is not displayed');
assert.equal((providerUi.match(/data-provider-field="imageModel"/g) || []).length, 1, 'image model should only appear once in the optional model section');
assert.equal((providerUi.match(/data-provider-field="chatModel"/g) || []).length, 1, 'chat model should only appear once per template');
assert.equal((providerUi.match(/data-provider-field="videoModel"/g) || []).length, 1, 'video model should only appear once per template');
assert.match(styles, /\.api-provider-step\{/);
assert.match(styles, /\.api-provider-model-focus\{/);
assert.match(styles, /\.api-provider-advanced-body\{/);
assert.match(styles, /\.api-provider-setup-checks\{/);
assert.match(styles, /\.provider-auto-setup-result\{/);

console.log('API settings simplicity tests passed.');
