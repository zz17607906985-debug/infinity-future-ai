'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const fsp = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const {chromium} = require(process.env.FUTURE_AI_PLAYWRIGHT_MODULE || 'playwright');
const {buildZip} = require('../src/runtime/zip-utils');
const imports = require('../src/media/short-import-service');
const root = path.join(__dirname, '..');
async function main() {
  const directory = await fsp.mkdtemp(path.join(os.tmpdir(), 'short-import-ui-'));
  const browser = await chromium.launch({headless: true, ...(process.env.FUTURE_AI_BROWSER_EXECUTABLE ? {executablePath: process.env.FUTURE_AI_BROWSER_EXECUTABLE} : {})});
  const page = await browser.newPage({viewport: {width: 1280, height: 900}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.exposeFunction('parseScriptFixture', payload => imports.readScriptImport({...payload, bytes: Buffer.from(payload.bytes)}));
    await page.exposeFunction('importSkillFixture', payload => imports.storeSkillImport(directory, {...payload, bytes: Buffer.from(payload.bytes)}));
    await page.exposeFunction('readSkillFixture', payload => imports.readSkillPackage(directory, payload.packageId, payload.context));
    const html = fs.readFileSync(path.join(root, 'src/index.html'), 'utf8');
    const story = html.slice(html.indexOf('<section id="shortStory"'), html.indexOf('<section id="shortStoryboard"'));
    const skillLine = html.split('\n').find(line => line.includes('id="shortSkillFile"'));
    await page.setContent('<body class="dark-mode nexus-layout"><h2>隔离导入测试 · 不修改用户项目</h2>' + skillLine + story + '</body>');
    for (const file of ['src/styles.css', 'src/media/short-asset-pipeline.css']) await page.addStyleTag({content: fs.readFileSync(path.join(root, file), 'utf8')});
    for (const file of ['src/short-batch-coordinator.js', 'src/media/short-workbench.js']) await page.addScriptTag({content: fs.readFileSync(path.join(root, file), 'utf8')});
    await page.evaluate(() => {
      const storage = new Map();
      Object.defineProperty(window, 'localStorage', {value: {getItem: key => storage.get(key) || null, setItem: (key, value) => storage.set(key, value), removeItem: key => storage.delete(key)}});
      window.codexBridge = {readScriptImport: payload => parseScriptFixture({...payload, bytes: Array.from(payload.bytes)}), importSkillPackage: payload => importSkillFixture({...payload, bytes: Array.from(payload.bytes)}), readSkillPackage: readSkillFixture};
      const host = {assetItems: [{id: 'keep-me'}], storyboardItems: [], audioPlan: [], timelineItems: [], qcItems: [], shortTaskCoordinator: window.FutureAIShortBatch.createCoordinator()};
      const notices = [];
      const $ = id => document.getElementById(id);
      const workbench = window.FutureAIShortWorkbench.create({host, $, esc: value => String(value ?? '').replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('"', '&quot;'), shortError: error => error.message || String(error), safeMediaUrl: value => value || '', saveProject: () => {}, queueSave: () => {}, toast: (message, kind) => notices.push({message, kind})});
      $('shortStoryText').value = '原有剧本，必须等用户确认后才能替换。';
      window.fixture = {host, workbench, storage, notices};
    });
    const app = fs.readFileSync(path.join(root, 'src/app.js'), 'utf8');
    const scriptBinding = app.split('\n').find(line => line.includes("$('shortStoryFile')?.addEventListener('change'"));
    const skillBinding = app.slice(app.indexOf("    $('shortSkillFile')?.addEventListener('change'"), app.indexOf("    $('shortRunLocalQc')?.addEventListener"));
    await page.evaluate(({scriptBinding, skillBinding}) => {
      const $ = id => document.getElementById(id);
      new Function('$', 'importShortScript', scriptBinding)($, fixture.workbench.importShortScript);
      new Function('$', 'shortWorkbench', 'shortSkillSelector', 'toast', skillBinding)($, () => fixture.workbench, $('shortSkillSelector'), (message, kind) => fixture.notices.push({message, kind}));
    }, {scriptBinding, skillBinding});
    const episode = number => ({name: '第' + number + '集.txt', mimeType: 'text/plain', buffer: Buffer.from('第' + number + '集：林青在车站寻找钥匙。旅人解释这把钥匙的来历，二人决定一起调查。')});
    await page.locator('#shortStoryFile').setInputFiles([episode(10), episode(2)]);
    await page.getByRole('dialog', {name: '预览剧本导入'}).waitFor();
    const preview = await page.locator('.short-import-confirm pre').innerText();
    assert.ok(preview.indexOf('1. 第2集.txt') < preview.indexOf('2. 第10集.txt'));
    assert.ok(preview.includes('清空'));
    await page.getByRole('button', {name: '取消，保留原内容', exact: true}).click();
    assert.equal(await page.evaluate(() => fixture.host.assetItems[0].id), 'keep-me');
    assert.ok((await page.locator('#shortStoryText').inputValue()).startsWith('原有剧本'));
    await page.locator('#shortStoryFile').setInputFiles([episode(10), episode(2)]);
    await page.getByRole('button', {name: '确认导入', exact: true}).click();
    await page.waitForFunction(() => document.getElementById('shortScriptImportStatus').textContent.includes('正文未截断'));
    const body = await page.locator('#shortStoryText').inputValue();
    assert.ok(body.indexOf('第2集') < body.indexOf('第10集'));
    assert.equal(await page.evaluate(() => fixture.host.assetItems.length), 0);
    await page.locator('#shortStoryFile').setInputFiles({name: '坏.docx', mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', buffer: Buffer.from('not a zip')});
    await page.waitForFunction(() => document.getElementById('shortScriptImportStatus').textContent.includes('导入失败'));
    assert.equal(await page.locator('#shortStoryText').inputValue(), body);
    const skill = '# 测试 Skill\n' + '依据剧本事实编译美术资产，不自动执行任何脚本。'.repeat(6) + '\n[资料](references/rules.md)';
    const archive = buildZip([{name: 'test/SKILL.md', data: skill}, {name: 'test/references/rules.md', data: '包内引用资料必须保留'}, {name: 'test/scripts/run.js', data: 'throw Error("never execute")'}]);
    await page.locator('#shortSkillFile').setInputFiles({name: '测试.zip', mimeType: 'application/zip', buffer: archive});
    await page.getByRole('dialog', {name: '确认导入 Skill'}).waitFor();
    assert.ok((await page.locator('.short-import-confirm pre').innerText()).includes('3 个文件'));
    await page.getByRole('button', {name: '取消，保留原内容', exact: true}).click();
    assert.equal(await page.evaluate(() => fixture.storage.has('futureai.shortSkillMeta.script-to-asset-ledger')), false);
    await page.locator('#shortSkillFile').setInputFiles({name: '测试.zip', mimeType: 'application/zip', buffer: archive});
    await page.getByRole('button', {name: '确认导入', exact: true}).click();
    await page.waitForFunction(() => fixture.storage.has('futureai.shortSkillMeta.script-to-asset-ledger'));
    const first = await page.evaluate(() => JSON.parse(fixture.storage.get('futureai.shortSkillMeta.script-to-asset-ledger')).active);
    assert.equal(first.fileCount, 3);
    await page.locator('#shortSkillFile').setInputFiles({name: '更新.md', mimeType: 'text/markdown', buffer: Buffer.from(skill + '\n第二版本')});
    await page.getByRole('button', {name: '确认导入', exact: true}).click();
    await page.waitForFunction(() => JSON.parse(fixture.storage.get('futureai.shortSkillMeta.script-to-asset-ledger')).history.length === 1);
    await page.evaluate(() => fixture.workbench.openShortSkillManager('script-to-asset-ledger'));
    await page.locator('[data-short-skill-restore="0"]').click();
    assert.equal(await page.evaluate(() => JSON.parse(fixture.storage.get('futureai.shortSkillMeta.script-to-asset-ledger')).active.packageId), first.packageId);
    await page.locator('#shortStoryFile').setInputFiles(Array.from({length: 80}, (_, index) => episode(80 - index)));
    await page.getByRole('dialog', {name: '预览剧本导入'}).waitFor();
    assert.ok((await page.locator('.short-import-confirm pre').innerText()).includes('80 个文件'));
    if (process.env.FUTURE_AI_UI_EVIDENCE_DIR) await page.screenshot({path: path.join(process.env.FUTURE_AI_UI_EVIDENCE_DIR, 'script-import-80-preview.png')});
    await page.getByRole('button', {name: '取消，保留原内容', exact: true}).click();
    assert.deepEqual(errors, []);
    console.log('Import UI passed: real file inputs, natural episode order, 80-file preview, cancel keeps data, malformed DOCX rejection, ZIP metadata, MD replacement and ZIP version restore.');
  } finally {
    await browser.close();
    const resolved = path.resolve(directory);
    assert.ok(resolved.startsWith(path.resolve(os.tmpdir()) + path.sep) && path.basename(resolved).startsWith('short-import-ui-'));
    await fsp.rm(resolved, {recursive: true, force: true});
  }
}
main().catch(error => {console.error(error); process.exitCode = 1;});
